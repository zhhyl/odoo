#!/usr/bin/env bash
# entrypoint.sh — Odoo container startup.
#
# Responsibilities:
#   1. Wait for Postgres to accept connections (the `db` service in compose).
#   2. Render /etc/odoo/odoo.conf from environment variables if no config is
#      mounted at that path.
#   3. Decide whether to bootstrap the database (first run / empty schema)
#      or just start the server.
#   4. Hand off to `odoo-bin` with whatever arguments were passed to the
#      container (so `docker run ... odoo-bin shell -d mydb` still works).

set -Eeuo pipefail

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
log()  { printf '[odoo-entrypoint] %s\n' "$*"; }
fail() { printf '[odoo-entrypoint] ERROR: %s\n' "$*" >&2; exit 1; }

PGCONN=( -h "${PGHOST:-db}" -p "${PGPORT:-5432}" -U "${PGUSER:-odoo}" )
export PGPASSWORD="${PGPASSWORD:-odoo}"

# Wait until `psql` can connect. Bounded by ${DB_WAIT_TIMEOUT:-60} seconds.
wait_for_postgres() {
    local timeout="${DB_WAIT_TIMEOUT:-60}"
    local start=$(date +%s)

    log "waiting for Postgres at ${PGHOST:-db}:${PGPORT:-5432} as ${PGUSER:-odoo} (timeout=${timeout}s) …"
    until psql "${PGCONN[@]}" -d "${PGDATABASE:-postgres}" -c 'SELECT 1' >/dev/null 2>&1; do
        local now=$(date +%s)
        if (( now - start > timeout )); then
            fail "Postgres did not become ready in ${timeout}s"
        fi
        sleep 1
    done
    log "Postgres is ready."
}

# Does the target Odoo database exist (regardless of schema state)?
db_exists() {
    local db="${1:-${ODOO_DB:-odoo}}"
    psql "${PGCONN[@]}" -d postgres -tAc \
        "SELECT 1 FROM pg_database WHERE datname='${db}'" \
        | grep -q 1
}

# Does the Odoo base schema look installed? (the `ir_module_module` table
# is created by Odoo on first install of the `base` module).
bootstrap_needed() {
    local db="${1:-${ODOO_DB:-odoo}}"
    if ! db_exists "$db"; then
        return 0  # DB missing ⇒ bootstrap required
    fi
    local count
    count=$(psql "${PGCONN[@]}" -d "$db" -tAc \
        "SELECT COUNT(*) FROM information_schema.tables \
         WHERE table_schema='public' AND table_name='ir_module_module'" \
        2>/dev/null || echo 0)
    [[ "${count:-0}" -eq 0 ]]
}

# Render /etc/odoo/odoo.conf unless one was bind-mounted.
# NOTE: the `dbfilter` option takes no underscore — it's a dest name from
# `--db-filter` in `odoo/tools/config.py`.
render_config() {
    local cfg="${ODOO_RC:-/etc/odoo/odoo.conf}"

    # If a config file exists, treat it as user-provided and skip
    # rendering — UNLESS it's one we generated on a previous boot, in
    # which case we want to re-render so env-var tweaks take effect.
    if [[ -f "${cfg}" && -s "${cfg}" ]]; then
        if grep -q 'Auto-generated by entrypoint.sh' "${cfg}"; then
            log "found a previous auto-generated ${cfg}, regenerating"
            rm -f "${cfg}"
        else
            log "using existing user-supplied config at ${cfg}"
            return
        fi
    fi

    log "rendering ${cfg} from environment"
    cat > "${cfg}" <<EOF
[options]
; Auto-generated by entrypoint.sh. Mount a custom file at this path
; to override any value below.
admin_passwd    = ${ODOO_ADMIN_PASSWD:-admin}
db_host          = ${PGHOST:-db}
db_port          = ${PGPORT:-5432}
db_user          = ${PGUSER:-odoo}
db_password      = ${PGPASSWORD:-odoo}
db_name          = ${ODOO_DB:-odoo}
dbfilter         = ${ODOO_DB_FILTER:-^${ODOO_DB:-odoo}\$}
addons_path      = ${ODOO_ADDONS_PATH:-/opt/odoo/src/addons,/opt/odoo/src/odoo/addons}
data_dir         = ${ODOO_DATA_DIR:-/var/lib/odoo/.local/share/Odoo}
logfile          = ${ODOO_LOGFILE:-/var/log/odoo/odoo.log}
log_level        = ${ODOO_LOG_LEVEL:-info}
http_port        = ${ODOO_HTTP_PORT:-8069}
http_interface   = ${ODOO_HTTP_INTERFACE:-0.0.0.0}
gevent_port      = ${ODOO_GEVENT_PORT:-8072}
gevent_interface = ${ODOO_GEVENT_INTERFACE:-0.0.0.0}
workers          = ${ODOO_WORKERS:-0}
max_cron_threads = ${ODOO_MAX_CRON_THREADS:-2}
limit_memory_hard = ${ODOO_LIMIT_MEMORY_HARD:-0}
limit_memory_soft = ${ODOO_LIMIT_MEMORY_SOFT:-2147483648}
limit_time_real   = ${ODOO_LIMIT_TIME_REAL:-0}
limit_time_cpu    = ${ODOO_LIMIT_TIME_CPU:-60}
limit_request     = ${ODOO_LIMIT_REQUEST:-0}
list_db           = ${ODOO_LIST_DB:-True}
EOF
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
wait_for_postgres
render_config

# If the user invoked the container with arguments:
#
#   - `docker compose run odoo shell -d mydb` → odoo sub-command, dispatch
#   - `docker compose exec odoo bash -lc "…"` → pass through to bash/sh
#   - `docker compose run odoo odoo-bin ...` → pass through to odoo-bin
#
# CMD is intentionally empty, so a normal `docker compose up -d` gives
# `$# == 0` and falls through to bootstrap / normal start.
if [[ $# -ge 1 ]]; then
    case "$1" in
        bash|sh|psql|python|python3|odoo-bin)
            # Run the requested tool directly (without our `-c odoo.conf`).
            log "passing through: $*"
            exec "$@"
            ;;
        *)
            log "executing: odoo-bin $*"
            exec odoo-bin -c "${ODOO_RC:-/etc/odoo/odoo.conf}" "$@"
            ;;
    esac
fi

# Bootstrap / normal start path --------------------------------------------
case "${ODOO_BOOTSTRAP:-auto}" in
    skip)
        log "ODOO_BOOTSTRAP=skip — starting in normal mode"
        exec odoo-bin -c "${ODOO_RC:-/etc/odoo/odoo.conf}"
        ;;
    force)
        log "ODOO_BOOTSTRAP=force — running -i ${ODOO_INIT_MODULES:-base}"
        exec odoo-bin -c "${ODOO_RC:-/etc/odoo/odoo.conf}" \
            -d "${ODOO_DB:-odoo}" \
            -i "${ODOO_INIT_MODULES:-base}" \
            --stop-after-init \
            --without-demo="${ODOO_WITHOUT_DEMO:-False}"
        ;;
    auto|"")
        if bootstrap_needed "${ODOO_DB:-odoo}"; then
            log "database '${ODOO_DB:-odoo}' not initialised — installing base"
            exec odoo-bin -c "${ODOO_RC:-/etc/odoo/odoo.conf}" \
                -d "${ODOO_DB:-odoo}" \
                -i "${ODOO_INIT_MODULES:-base}" \
                --stop-after-init \
                --without-demo="${ODOO_WITHOUT_DEMO:-False}"
        fi

        if [[ -n "${ODOO_UPDATE_MODULES:-}" ]]; then
            log "updating modules: ${ODOO_UPDATE_MODULES}"
            exec odoo-bin -c "${ODOO_RC:-/etc/odoo/odoo.conf}" \
                -d "${ODOO_DB:-odoo}" \
                -u "${ODOO_UPDATE_MODULES}" \
                --stop-after-init
        fi

        log "database already initialised — starting server"
        exec odoo-bin -c "${ODOO_RC:-/etc/odoo/odoo.conf}"
        ;;
    *)
        fail "unknown ODOO_BOOTSTRAP mode: '${ODOO_BOOTSTRAP:-auto}' (expected: auto|skip|force)"
        ;;
esac
